import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ROOT_DIR = import.meta.dirname
  ? path.resolve(import.meta.dirname, '..')
  : process.cwd();
const DIST_DIR = path.join(ROOT_DIR, 'dist');

const IGNORED_FILES = new Set(['sw.js', '.nojekyll']);

function collectFiles(dir, baseDir, out = []) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const relPath = path.relative(baseDir, fullPath).split(path.sep).join('/');

    if (entry.isDirectory()) {
      collectFiles(fullPath, baseDir, out);
    } else if (entry.isFile()) {
      if (!IGNORED_FILES.has(relPath)) {
        out.push({ fullPath, relPath });
      }
    }
  }
  return out;
}

function main() {
  if (!fs.existsSync(DIST_DIR)) {
    console.error(`[build-sw] Error: dist directory not found at ${DIST_DIR}. Run vite build first.`);
    process.exit(1);
  }

  const files = collectFiles(DIST_DIR, DIST_DIR);
  if (files.length === 0) {
    console.error('[build-sw] Error: dist directory is empty.');
    process.exit(1);
  }

  const hasher = crypto.createHash('sha256');
  const precacheSet = new Set(['./']);

  for (const file of files) {
    const content = fs.readFileSync(file.fullPath);
    hasher.update(file.relPath);
    hasher.update('\0');
    hasher.update(content);
    precacheSet.add(`./${file.relPath}`);
  }

  const buildHash = hasher.digest('hex').slice(0, 10);
  const precacheUrls = Array.from(precacheSet);

  // Ensure GitHub Pages serves dotfiles / assets without Jekyll processing
  fs.writeFileSync(path.join(DIST_DIR, '.nojekyll'), '');

  const swSource = `// Auto-generated by scripts/build-sw.mjs — do not edit manually
const BUILD_HASH = ${JSON.stringify(buildHash)};
const CACHE_PREFIX = 'overtone-chladni-cache-';
const CACHE_NAME = 'overtone-chladni-cache-v1-' + BUILD_HASH;
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      );
      await self.clients.claim();
      const clients = await self.clients.matchAll({
        type: 'window',
        includeUncontrolled: true,
      });
      for (const client of clients) {
        client.postMessage({ type: 'OVERTONE_SW_READY', cacheName: CACHE_NAME });
      }
    })()
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const reqUrl = new URL(request.url);
  if (reqUrl.origin !== self.location.origin) return;

  const strippedUrl = reqUrl.origin + reqUrl.pathname;
  const scopePath = new URL('./', self.registration.scope).pathname;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE_NAME);

      // Strip query strings so ./?source=pwa matches precached ./ or ./index.html
      let cached = await cache.match(strippedUrl);
      if (!cached) {
        cached = await cache.match(request, { ignoreSearch: true });
      }
      if (!cached && (reqUrl.pathname === scopePath || reqUrl.pathname.endsWith('/'))) {
        cached = await cache.match('./index.html');
      }
      if (cached) {
        return cached;
      }

      try {
        return await fetch(request);
      } catch (err) {
        if (request.mode === 'navigate') {
          const fallback = await cache.match('./index.html');
          if (fallback) return fallback;
        }
        throw err;
      }
    })()
  );
});
`;

  const swPath = path.join(DIST_DIR, 'sw.js');
  fs.writeFileSync(swPath, swSource, 'utf8');
  console.log(
    `[build-sw] Generated dist/sw.js (hash=${buildHash}, precached=${precacheUrls.length} URLs) and dist/.nojekyll`
  );
}

main();
